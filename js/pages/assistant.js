const STORE_KEY = 'omt:chat';
const WELCOME = "Hi! I'm OMT AI. Tell me what you're trying to learn or which book you're looking for, and I'll help you find the right resources.";

const params = new URLSearchParams(location.search);
let mode = 'demo';
let catalog = [];
let resource = null;
let busy = false;
/** @type {{role:'user'|'assistant', content:string, resources?:object[], mode?:string}[]} */
let history = [];

// Conversation lives in sessionStorage: kept while the tab is open, gone when it closes.
function save() {
  try { sessionStorage.setItem(STORE_KEY, JSON.stringify({ resourceId: resource?.id ?? null, history: history.slice(-30) })); } catch { /* storage blocked */ }
}
function restore() {
  try { return JSON.parse(sessionStorage.getItem(STORE_KEY) ?? 'null'); } catch { return null; }
}

// ---------- Rendering ----------
const SOURCE_NAMES = { googlebooks: 'Google Books', openlibrary: 'Open Library', gutenberg: 'Project Gutenberg' };

function recHTML(rec) {
  const url = safeUrl(rec.url);
  if (!url) return '';
  const external = /^https?:/.test(url);
  // Live answers carry an OMT access type; demo Open Library records carry Open Library's own access field.
  const a = rec.accessType ? (ACCESS[rec.accessType] ?? ACCESS.info) : (OL_ACCESS[rec.access] ?? OL_ACCESS.no_ebook);
  const badge = `<span class="badge badge--${a.badge}" title="${e(a.explain ?? a.title ?? '')}">${e(a.label)}</span>`;
  const sourceNote = rec.source !== 'omt'
    ? `${e(SOURCE_NAMES[rec.source] ?? 'External')}${rec.year ? ` · ${e(rec.year)}` : ''}`
    : (rec.why ? e(rec.why) : 'In the OMT library');
  const added = rec.addedToLibrary ? `<span class="rec__added">${icons.sparkle.replace('<svg', '<svg width="12" height="12"')} Added to the OMT library</span>` : '';
  return `<div class="rec"><div class="rec__top"><a href="${e(url)}"${external ? ' target="_blank" rel="noopener noreferrer"' : ''}>${e(rec.title)}${external ? '<span class="sr-only"> (opens in a new tab)</span>' : ''}</a>${badge}</div>
    <span class="rec__why">${rec.author ? `${e(rec.author)} · ` : ''}${sourceNote}</span>${added}</div>`;
}

// Live answers may link only to pages from their search results, the site itself, and book searches.
const SEARCH_LINK = /^https:\/\/(openlibrary\.org\/search\?|www\.google\.com\/search\?tbm=bks&)/;
function linkPolicy(msg) {
  if (msg.mode !== 'live') return undefined;
  const allowed = new Set(msg.links ?? []);
  return { allowLink: (url) => !/^https:/.test(url) || allowed.has(url) || SEARCH_LINK.test(url) };
}

function followupsHTML(msg) {
  if (!msg.followups?.length) return '';
  return `<div class="msg__followups" aria-label="Suggested follow-up questions">${msg.followups.map((f) => `<button type="button" class="chip chip--ask" data-prompt="${e(f)}">${e(f)}</button>`).join('')}</div>`;
}

function aiBodyHTML(msg) {
  const recs = (msg.resources ?? []).map(recHTML).join('');
  return `${renderMarkdown(msg.content, linkPolicy(msg))}${recs ? `<div class="msg__recs">${recs}</div>` : ''}`;
}

function messageHTML(msg, isLast = false) {
  if (msg.role === 'user') return `<div class="msg msg--user"><span class="sr-only">You said:</span>${renderMarkdown(msg.content)}</div>`;
  const label = msg.mode === 'live'
    ? `<div class="msg__label">${icons.sparkle.replace('<svg', '<svg width="14" height="14"')} OMT AI</div>`
    : msg.mode === 'demo'
      ? '<div class="msg__label"><span class="badge badge--demo">Demo response</span> prepared answer, not generated by an AI model</div>'
      : '<div class="msg__label">OMT AI</div>';
  return `<div class="msg msg--ai">${label}<div class="msg__body">${aiBodyHTML(msg)}</div>${isLast ? followupsHTML(msg) : ''}</div>`;
}

function renderAll() {
  els.log.innerHTML = messageHTML({ role: 'assistant', content: WELCOME }) + history.map((m, i) => messageHTML(m, i === history.length - 1)).join('');
  scrollDown();
}
function append(msg) {
  els.log.querySelectorAll('.msg__followups').forEach((el) => el.remove());
  els.log.insertAdjacentHTML('beforeend', messageHTML(msg, true));
  scrollDown();
}
function scrollDown() { els.log.scrollTo({ top: els.log.scrollHeight, behavior: 'instant' }); }

function renderSuggestions() {
  const prompts = resource
    ? ['Explain what this resource is about', 'Give me an overview', 'Who is this for?', 'Suggest free alternatives']
    : ['Explain subnetting like I\'m a beginner', 'What is the difference between 4G and 5G core?', 'Recommend a free book to learn Linux', 'How do Docker and Kubernetes fit together?', 'TCP vs UDP', 'Help me learn networking from scratch', 'Explain Excel VLOOKUP'];
  els.suggestions.innerHTML = prompts.map((p) => `<li><button type="button" class="chip" data-prompt="${e(p)}">${e(p)}</button></li>`).join('');
}

function renderContext() {
  if (!resource) { els.context.innerHTML = ''; return; }
  els.context.innerHTML = `<div class="context-pill">${icons.book.replace('<svg', '<svg width="18" height="18"')}<span>Asking about: <a href="resource.html?id=${encodeURIComponent(resource.id)}"><strong>${e(resource.title)}</strong></a></span><button type="button" class="btn btn--ghost btn--sm" id="drop-context" aria-label="Stop asking about this resource">${icons.close.replace('<svg', '<svg width="16" height="16"')}</button></div>`;
  $('#drop-context').addEventListener('click', () => {
    resource = null;
    history.push({ role: 'assistant', content: 'Okay, I\'m no longer focused on that resource. What else can I help with?', mode });
    renderContext(); renderSuggestions(); renderAll(); save();
    const url = new URL(location.href); url.searchParams.delete('resource'); window.history.replaceState(null, '', url);
  });
}

const SEND_ICON = els.send.innerHTML;
const STOP_ICON = '<span class="sr-only">Stop</span><svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><rect x="6" y="6" width="12" height="12" rx="2"/></svg>';
let controller = null;

function setBusy(on) {
  busy = on;
  // While OMT AI answers, the send button becomes a stop button.
  els.send.innerHTML = on ? STOP_ICON : SEND_ICON;
  els.send.classList.toggle('is-stop', on);
  els.input.setAttribute('aria-busy', String(on));
  const typing = $('#typing');
  if (on && !typing) els.log.insertAdjacentHTML('beforeend', '<div class="msg msg--ai typing" id="typing" role="status"><span></span><span></span><span></span><em>Searching books…</em></div>');
  if (!on) typing?.remove();
  scrollDown();
}

// ---------- AI calls ----------
class FriendlyError extends Error {}

/** A message bubble that fills in while the answer streams. */
function startLiveBubble() {
  $('#typing')?.remove();
  els.log.querySelectorAll('.msg__followups').forEach((el) => el.remove());
  els.log.insertAdjacentHTML('beforeend', `<div class="msg msg--ai is-streaming"><div class="msg__label">${icons.sparkle.replace('<svg', '<svg width="14" height="14"')} OMT AI</div><div class="msg__body"></div></div>`);
  const el = els.log.lastElementChild;
  const bodyEl = el.querySelector('.msg__body');
  let text = '';
  let frame = 0;
  const paint = () => { frame = 0; bodyEl.innerHTML = `${renderMarkdown(text)}<span class="caret" aria-hidden="true"></span>`; scrollDown(); };
  return {
    get text() { return text; },
    add(piece) { text += piece; if (!frame) frame = requestAnimationFrame(paint); },
    finish(msg) { cancelAnimationFrame(frame); el.outerHTML = messageHTML(msg, true); scrollDown(); },
    remove() { cancelAnimationFrame(frame); el.remove(); },
  };
}

async function liveReply() {
  controller = new AbortController();
  // Abort only if nothing arrives for a while; a long answer that keeps streaming is fine.
  let timer = setTimeout(() => controller.abort('timeout'), 30_000);
  const bump = () => { clearTimeout(timer); timer = setTimeout(() => controller.abort('timeout'), 30_000); };
  let bubble = null;
  try {
    const res = await fetch(SITE.aiEndpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Accept: 'application/x-ndjson' },
      body: JSON.stringify({
        stream: true,
        messages: history.slice(-12).map(({ role, content }) => ({ role, content: content.slice(0, 2000) })),
        resourceId: resource?.id ?? null,
      }),
      signal: controller.signal,
    });
    if (!(res.headers.get('content-type') ?? '').includes('ndjson')) {
      let data = null;
      try { data = await res.json(); } catch { /* non-JSON */ }
      if (res.ok && data?.ok) return { reply: data.reply, resources: data.resources ?? [], followups: data.followups, links: data.links, mode: 'live' };
      if (data?.error?.code === 'not_configured') { setMode('demo'); return null; }
      throw new FriendlyError(data?.error?.message ?? (res.status === 429 ? 'Too many requests. Please wait a moment.' : 'OMT AI is having trouble right now. Please try again shortly.'));
    }

    bubble = startLiveBubble();
    const reader = res.body.pipeThrough(new TextDecoderStream()).getReader();
    let buffer = '';
    for (;;) {
      const { value, done } = await reader.read();
      if (done) break;
      bump();
      buffer += value;
      const lines = buffer.split('\n');
      buffer = lines.pop();
      for (const line of lines) {
        if (!line.trim()) continue;
        const event = JSON.parse(line);
        if (event.type === 'delta') bubble.add(event.text);
        else if (event.type === 'done') return { reply: event.reply, resources: event.resources ?? [], followups: event.followups, links: event.links, mode: 'live', bubble };
        else if (event.type === 'error') throw new FriendlyError(event.error?.message ?? 'OMT AI is having trouble right now. Please try again shortly.');
      }
    }
    throw new FriendlyError('The answer was cut off. Please try again.');
  } catch (err) {
    // Stopped by the user: keep whatever was written so far.
    if (controller.signal.aborted && controller.signal.reason !== 'timeout') {
      if (bubble?.text.trim()) return { reply: `${bubble.text.trim()}\n\n*(stopped)*`, resources: [], mode: 'live', bubble };
      bubble?.remove();
      return { stopped: true };
    }
    bubble?.remove();
    if (err instanceof FriendlyError) throw err;
    if (controller.signal.aborted) throw new FriendlyError('OMT AI took too long to answer. Please try again.');
    throw new FriendlyError(navigator.onLine ? 'Couldn\'t reach OMT AI. Please try again.' : 'You appear to be offline. Check your connection and try again.');
  } finally {
    clearTimeout(timer);
    controller = null;
  }
}

async function respond() {
  setBusy(true);
  const last = history[history.length - 1];
  try {
    let result = mode === 'live' ? await liveReply() : null;
    if (result?.stopped) { setBusy(false); return; }
    if (!result) {
      const demo = await demoReply({ message: last.content, resource, all: catalog });
      result = { ...demo, mode: 'demo' };
    }
    setBusy(false);
    const msg = { role: 'assistant', content: result.reply, resources: result.resources, followups: result.followups, links: result.links, mode: result.mode };
    history.push(msg);
    if (result.bubble) result.bubble.finish(msg);
    else append(msg);
    save();
  } catch (err) {
    setBusy(false);
    els.log.insertAdjacentHTML('beforeend', `<div class="msg msg--error" role="alert"><p>${e(err.message)}</p><button type="button" class="btn btn--secondary btn--sm" data-retry>Try again</button></div>`);
    scrollDown();
  }
}

function send(text) {
  const content = text.trim().slice(0, 2000);
  if (!content || busy) return;
  history.push({ role: 'user', content });
  append({ role: 'user', content });
  save();
  els.input.value = '';
  autosize();
  respond();
}

function setMode(next) {
  mode = next;
  els.mode.className = `badge badge--${next === 'live' ? 'live' : 'demo'}`;
  els.mode.textContent = next === 'live' ? 'Live AI' : 'Demo mode';
  els.mode.title = next === 'live' ? 'Answers are generated by an AI model using our catalogue.' : 'No AI model is connected. Answers are prepared examples plus real catalogue search.';
}

async function detectMode() {
  try {
    const res = await fetch(SITE.aiEndpoint, { headers: { Accept: 'application/json' } });
    const data = res.ok ? await res.json() : null;
    setMode(data?.configured ? 'live' : 'demo');
  } catch {
    setMode('demo');
  }
}

// ---------- Events ----------
function autosize() {
  els.input.style.height = 'auto';
  els.input.style.height = `${Math.min(els.input.scrollHeight, 160)}px`;
}
els.input.addEventListener('input', autosize);
els.input.addEventListener('keydown', (event) => {
  if (event.key === 'Enter' && !event.shiftKey && !event.isComposing) { event.preventDefault(); send(els.input.value); }
});
els.form.addEventListener('submit', (event) => { event.preventDefault(); send(els.input.value); });
els.send.addEventListener('click', (event) => {
  if (!busy) return;
  event.preventDefault();
  controller?.abort('user');
});
els.suggestions.addEventListener('click', (event) => {
  const chip = event.target.closest('[data-prompt]');
  if (chip) send(chip.dataset.prompt);
});
els.log.addEventListener('click', (event) => {
  const ask = event.target.closest('[data-prompt]');
  if (ask && !busy) { send(ask.dataset.prompt); return; }
  if (!event.target.closest('[data-retry]') || busy) return;
  event.target.closest('.msg--error').remove();
  respond();
});
els.clear.addEventListener('click', () => {
  if (!history.length) return;
  if (!confirm('Clear this conversation? This cannot be undone.')) return;
  history = [];
  save();
  renderAll();
  els.input.focus();
});

// ---------- Start ----------
renderAll();
renderSuggestions();
const modeReady = detectMode();
try {
  catalog = await loadCatalog();
} catch (err) {
  append({ role: 'assistant', content: `I couldn't load the library catalogue, so my recommendations may be limited. (${err.message})` });
}

const saved = restore();
const resourceId = params.get('resource') ?? (params.has('q') ? null : saved?.resourceId);
if (resourceId) resource = catalog.find((r) => r.id === resourceId) ?? null;
if (saved?.history?.length && (saved.resourceId ?? null) === (resource?.id ?? null)) history = saved.history;
renderContext();
renderSuggestions();
renderAll();

await modeReady;
const initialQ = params.get('q');
if (initialQ) {
  const url = new URL(location.href); url.searchParams.delete('q'); window.history.replaceState(null, '', url);
  send(initialQ);
} else if (resource && !history.length) {
  send('Explain what this resource is about');
}
